export type PlanType = 'free' | 'pro' | 'enterprise';

export interface IUserProfile {
  name?: string;
  username: string;
  avatar?: string;
  bio?: string;
}

export interface IUserQuota {
  imagesRemaining: number;
  lastRefreshedAt?: Date;
}

export interface UserStatistics {
  lastLoginAt: Date; // Last login timestamp
  totalLogins: number; // Total number of logins
  imagesGenerated: number; // Total images generated by the user
}

export interface User {
  uid: string; // Firebase/Auth ID
  email: string;
  createdAt: Date;
  updatedAt: Date;
  profile: IUserProfile;
  planType: PlanType;
  quota: IUserQuota;
  statistics: UserStatistics;
  fcmToken?: string; // Firebase Cloud Messaging token
  fcmTokenUpdatedAt?: Date; // When the FCM token was last updated
}

// API Response types
export interface ApiResponse<T = any> {
  success: boolean;
  message: string;
  data?: T;
  error?: string;
  errors?: string[];
  requestId?: string;
}

export interface PaginatedResponse<T> {
  success: boolean;
  message: string;
  data: T[];
  pagination: {
    page: number;
    limit: number;
    total: number;
    totalPages: number;
    hasNext: boolean;
    hasPrev: boolean;
  };
  requestId?: string;
}

// Authentication types
export interface AuthUser {
  uid: string;
  email: string;
  profile: IUserProfile;
  planType: PlanType;
  quota: IUserQuota;
  statistics?: UserStatistics;
  createdAt?: Date;
  updatedAt?: Date;
}

// Form types
export interface LoginForm {
  email: string;
  password: string;
}

export interface RegisterForm {
  email: string;
  password: string;
  confirmPassword: string;
  username: string;
}

export interface ProfileUpdateForm {
  username: string;
  bio?: string;
  avatar?: string;
}

// Store types
export interface AuthState {
  user: AuthUser | null;
  isAuthenticated: boolean;
  isLoading: boolean;
  error: string | null;
}

export interface ImageStore {
  images: any[];
  isLoading: boolean;
  error: string | null;
  hasMore: boolean;
  page: number;
}

// Engine and generation types
export type EngineType = 'quantum' | 'nebula';
export type ImageSize = 'small' | 'medium' | 'large';

export interface GenerationSettings {
  engineType: EngineType;
  aspectRatio: string;
  imageSize: ImageSize;
  styles: string[];
  seed: number;
  negativePrompt: string;
  isPrivate: boolean;
  batchCount: number;
}

// Image response types
export interface GeneratedImage {
  id: string;
  userId: string;
  prompt: string;
  imageUrl: string;
  thumbnailUrl: string;
  engineType: EngineType;
  styles?: string[];
  width: number;
  height: number;
  seed: number;
  imageSize: ImageSize;
  aspectRatio: string;
  negativePrompt?: string;
  isFavorite?: boolean;
  isPrivate: boolean;
  createdAt: Date;
  userName: string;
  userAvatar: string;
  batchId?: string;
  batchTimestamp?: Date;
}

// Quota types for frontend
export interface QuotaInfo {
  imagesRemaining: number;
  lastRefreshedAt?: string;
  nextRefreshAt?: string; // For display purposes
  planLimits?: {
    totalImages: number;
  };
}

// Error types
export interface AppError {
  message: string;
  code?: string;
  statusCode?: number;
  timestamp?: Date;
}
