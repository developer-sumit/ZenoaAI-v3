export type PlanType = 'free' | 'pro' | 'enterprise';

export interface IUserProfile {
  username: string;
  avatar?: string;
  bio?: string;
}

export interface IUserQuota {
  imagesRemaining: number;
  refreshAt: Date;
}

export interface UserStatistics {
  lastLoginAt: Date; // Last login timestamp
  totalLogins: number; // Total number of logins
  imagesGenerated: number; // Total images generated by the user
}

export interface User {
  uid: string; // Firebase/Auth ID
  email: string;
  createdAt: Date;
  updatedAt: Date;
  lastLoginAt?: Date; // For backward compatibility
  isDeleted?: boolean;
  deletedAt?: Date;
  profile: IUserProfile;
  planType: PlanType;
  quota: IUserQuota;
  statistics: UserStatistics;
  fcmToken?: string; // Firebase Cloud Messaging token
  fcmTokenUpdatedAt?: Date; // When the FCM token was last updated
}

export type EngineType = 'quantum' | 'nebula';
export type AspectRatioSize = 'small' | 'medium' | 'large';

export interface AspectRatio {
  ratio: string;
  sizes: {
    small: string;
    medium: string;
    large: string;
  };
  size?: AspectRatioSize;
}

export interface ArtStyleType {
  id: string;
  name: string;
  image: string;
}

export interface QualityPresetType {
  label: string;
  value: number;
}

export interface GeneratedImage {
  id: string;
  userId: string;
  engineType: EngineType;
  originalPrompt: string; // User's original input
  finalPrompt: string; // Enhanced prompt with style details
  negativePrompt?: string;
  imageUrl: string; // Primary image URL (Cloudinary)
  thumbnailUrl?: string; // Optimized thumbnail URL
  width: number;
  height: number;
  styles?: string[]; // Array of style names applied
  seed: number;
  sampler?: string;
  steps?: number;
  createdAt: Date | string;
  isFavorite?: boolean;
  isPrivate: boolean;

  // Additional fields for UI
  userName?: string;
  userAvatar?: string;

  // Legacy/compatibility fields
  uri?: string; // Alias for imageUrl
  prompt?: string; // For backward compatibility
  aspectRatio?: AspectRatio;
  quality?: number;
  timestamp?: number;
  loading?: boolean;
  error?: boolean;
  index?: number;
  isDeleted?: boolean;
  deletedAt?: string;
  updatedAt?: string;

  // Server-specific fields
  favorite?: boolean; // Server uses 'favorite' instead of 'isFavorite'
}

// Server response structures
export interface ImageGenerationResponse {
  success: boolean;
  imageUrl: string;
  originalUrl?: string;
  optimizedUrls?: {
    thumbnail: string;
    medium: string;
    webp: string;
    progressive: string;
  };
  metadata?: GeneratedImage;
  engineUsed?: EngineType;
  prompts?: {
    original: string;
    final: string;
  };
  cloudinary?: {
    publicId: string;
    format: string;
    size: number;
  };
  fallback?: boolean;
  message?: string;
}

export interface PaginatedResponse<T> {
  success: boolean;
  message: string;
  data: T[];
  pagination: {
    page: number;
    limit: number;
    total: number;
    totalPages: number;
    hasNext: boolean;
    hasPrev: boolean;
  };
  requestId?: string;
}

export interface ApiResponse<T = any> {
  success: boolean;
  message: string;
  data?: T;
  error?: string;
  errors?: string[];
  requestId?: string;
}

export interface ImageStats {
  totalImages: number;
  favoriteImages: number;
  privateImages: number;
  totalBytes: number;
  engineStats: string[];
}

export interface AvailableOptions {
  styles: ArtStyleType[];
  engines: {
    key: EngineType;
    name: string;
    description: string;
    isPremium: boolean;
    available: boolean;
  }[];
  aspectRatios: AspectRatio[];
  userPlan: string;
  planLimits: {
    totalImages: number;
    totalApiCalls: number;
  };
}

// Image generation request interface to match server
export interface ImageGenerationRequest {
  userId?: string;
  engineType: EngineType;
  prompt: string;
  width: number;
  height: number;
  aspectRatio: string; // e.g., "1:1", "16:9", etc.
  styles?: string[];
  sampler?: string;
  steps?: number;
  seed?: number;
  negativePrompt?: string;
  imageSize: AspectRatioSize;
  batchCount?: number;
  isPrivate?: boolean;
}

export interface ImageGeneration {
  id: string;
  prompt: string;
  fullPrompt: string;
  negativePrompt?: string;
  styles: string[];
  engine: EngineType;
  aspectRatio: AspectRatio;
  quality: 'high' | 'standard';
  sampler?: string;
  images: GeneratedImage[];
  synced?: boolean;
  isPrivate?: boolean;
  userId?: string;
  userName?: string;
  userAvatar?: string;
  createdAt: string;
  updatedAt: string;
}
